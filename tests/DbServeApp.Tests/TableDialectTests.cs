using DbServeApp.Services.Dbms;

namespace DbServeApp.Tests;

public class TableDialectTests
{
    private static ColumnDef Col(string name, string type = "int", bool pk = false, bool identity = false, bool nullable = true,
        int? length = null, string def = "") =>
        new() { Name = name, Type = type, PrimaryKey = pk, Identity = identity, Nullable = nullable, Length = length, Default = def };

    [Theory]
    [InlineData("postgres", "PostgreSQL")]
    [InlineData("POSTGRES", "PostgreSQL")]
    [InlineData("mariadb", "MariaDB SQL")]
    [InlineData("mysql", "MariaDB SQL")]
    [InlineData("mssql", "T-SQL")]
    [InlineData(null, "T-SQL")]
    [InlineData("unknown", "T-SQL")]
    public void For_PicksDialectByKey(string? key, string expected) => Assert.Equal(expected, TableDialect.For(key).Name);

    [Fact]
    public void Quote_EscapesPerDialect()
    {
        Assert.Equal("[a]]b]", TableDialect.Mssql.Quote("a]b"));
        Assert.Equal("\"a\"\"b\"", TableDialect.Postgres.Quote("a\"b"));
        Assert.Equal("`a``b`", TableDialect.MariaDb.Quote("a`b"));
    }

    [Fact]
    public void Mssql_BuildsCreateTable()
    {
        var t = new TableDef("dbo", "Users", [Col("Id", pk: true, identity: true, nullable: false), Col("Name", "nvarchar", length: 50)]);

        var sql = TableDialect.Mssql.Build(t);

        Assert.Contains("CREATE TABLE [dbo].[Users]", sql);
        Assert.Contains("[Id] INT IDENTITY(1,1) NOT NULL", sql);
        Assert.Contains("[Name] NVARCHAR(50) NULL", sql);
        Assert.Contains("CONSTRAINT [PK_Users] PRIMARY KEY ([Id])", sql);
        Assert.EndsWith(");", sql);
    }

    [Fact]
    public void Mssql_UseDatabase_IsPrepended()
    {
        var t = new TableDef("dbo", "T", [Col("Id")]);

        Assert.StartsWith("USE [shop];", TableDialect.Mssql.Build(t, "shop"));
    }

    [Fact]
    public void Postgres_BuildsCreateTable()
    {
        var t = new TableDef("public", "users", [Col("id", "integer", pk: true, identity: true, nullable: false), Col("name", "varchar", length: 40)]);

        var sql = TableDialect.Postgres.Build(t);

        Assert.Contains("CREATE TABLE \"public\".\"users\"", sql);
        Assert.Contains("\"id\" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL", sql);
        Assert.Contains("\"name\" varchar(40) NULL", sql);
        Assert.Contains("PRIMARY KEY (\"id\")", sql);
    }

    [Fact]
    public void Postgres_Use_EmitsConnectCommand()
    {
        Assert.Contains("\\connect \"shop\"", TableDialect.Postgres.Use("shop"));
        Assert.Equal("", TableDialect.Postgres.Use(" "));
    }

    [Fact]
    public void MariaDb_BuildsCreateTable_WithAutoIncrement()
    {
        var t = new TableDef("appdb", "users", [Col("id", pk: true, identity: true, nullable: false), Col("name", "varchar", length: 40)]);

        var sql = TableDialect.MariaDb.Build(t);

        Assert.Contains("CREATE TABLE `appdb`.`users`", sql);
        Assert.Contains("`id` int NOT NULL AUTO_INCREMENT", sql);
        Assert.Contains("`name` varchar(40) NULL", sql);
        Assert.Contains("PRIMARY KEY (`id`)", sql);
    }

    [Fact]
    public void MariaDb_VarcharWithoutLength_DefaultsTo255()
    {
        var t = new TableDef("appdb", "t", [Col("name", "varchar")]);

        Assert.Contains("varchar(255)", TableDialect.MariaDb.Build(t));
    }

    [Fact]
    public void MariaDb_Use_EmitsUseStatement() => Assert.Equal("USE `shop`;\n", TableDialect.MariaDb.Use("shop"));

    [Fact]
    public void DefaultExpression_IsWrapped()
    {
        var t = new TableDef("dbo", "T", [Col("Created", "datetime2", def: "GETDATE()")]);

        Assert.Contains("DEFAULT (GETDATE())", TableDialect.Mssql.Build(t));
    }

    [Theory]
    [InlineData("mssql")]
    [InlineData("postgres")]
    [InlineData("mariadb")]
    public void EmptyTable_FailsValidation(string key)
    {
        var errors = TableDialect.For(key).Validate(new TableDef("s", "", []));

        Assert.Contains(errors, e => e.Contains("Table name is required"));
        Assert.Contains(errors, e => e.Contains("at least one column"));
    }

    [Theory]
    [InlineData("mssql", "int")]
    [InlineData("postgres", "integer")]
    [InlineData("mariadb", "int")]
    public void DuplicateColumnNames_AreRejected(string key, string type)
    {
        var t = new TableDef("s", "t", [Col("a", type), Col("a", type)]);

        Assert.Contains(TableDialect.For(key).Validate(t), e => e.Contains("duplicate"));
    }

    [Theory]
    [InlineData("mssql", "int")]
    [InlineData("postgres", "integer")]
    [InlineData("mariadb", "int")]
    public void NullablePrimaryKey_IsRejected(string key, string type)
    {
        var t = new TableDef("s", "t", [Col("id", type, pk: true, nullable: true)]);

        Assert.Contains(TableDialect.For(key).Validate(t), e => e.Contains("primary key"));
    }

    [Fact]
    public void TwoIdentityColumns_AreRejected()
    {
        var t = new TableDef("dbo", "t", [Col("a", identity: true, nullable: false), Col("b", identity: true, nullable: false)]);

        Assert.Contains(TableDialect.Mssql.Validate(t), e => e.Contains("Only one identity"));
    }

    [Fact]
    public void MariaDb_AutoIncrementOutsidePrimaryKey_IsRejected()
    {
        var t = new TableDef("appdb", "t", [Col("a", identity: true, nullable: false)]);

        Assert.Contains(TableDialect.MariaDb.Validate(t), e => e.Contains("primary key"));
    }

    [Fact]
    public void UnsupportedType_IsRejected()
    {
        var t = new TableDef("dbo", "t", [Col("a", "banana")]);

        Assert.Contains(TableDialect.Mssql.Validate(t), e => e.Contains("unsupported type"));
    }

    [Fact]
    public void ValidTable_HasNoErrors()
    {
        var t = new TableDef("dbo", "t", [Col("id", pk: true, identity: true, nullable: false), Col("name", "nvarchar", length: 20)]);

        Assert.Empty(TableDialect.Mssql.Validate(t));
    }

    [Fact]
    public void MariaDb_HasNoSchemas_OthersDo()
    {
        Assert.False(TableDialect.MariaDb.HasSchemas);
        Assert.True(TableDialect.Mssql.HasSchemas);
        Assert.True(TableDialect.Postgres.HasSchemas);
    }
}
